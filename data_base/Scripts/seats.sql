CREATE TABLE SEATS(
    ID_SEAT NUMBER,
    SEAT_NUMBER NUMBER NOT NULL,
    SEAT_ROW VARCHAR2(1) NOT NULL,
    ID_SCREEN NUMBER NOT NULL,
    ID_SCREENING NUMBER NOT NULL,

    CONSTRAINT FK_SEATS_ID_SCREEN FOREIGN KEY (ID_SCREEN) REFERENCES SCREENS(ID_SCREEN),
    CONSTRAINT FK_SEATS_ID_SCREENING FOREIGN KEY (ID_SCREENING) REFERENCES SCREENINGS(ID_SCREENING),
    CONSTRAINT PK_SEAT PRIMARY KEY (ID_SEAT, ID_SCREEN, ID_SCREENING)
);

CREATE TABLE RESERVATIONS(
    ID_RESERVATION NUMBER GENERATED ALWAYS AS IDENTITY,
    RESERVED_UNTIL TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT PK_RESERVATION PRIMARY KEY (ID_RESERVATION)
);

CREATE TABLE RESERVATIONS_SEATS(
    ID_SEAT NUMBER NOT NULL,
    ID_SCREEN NUMBER NOT NULL,
    ID_SCREENING NUMBER NOT NULL,
    ID_RESERVATION NUMBER NOT NULL,

    CONSTRAINT PK_RES_SEAT PRIMARY KEY (ID_SEAT, ID_SCREEN, ID_SCREENING, ID_RESERVATION),
    CONSTRAINT FK_RES_SIT_RESERVATION FOREIGN KEY (ID_RESERVATION) REFERENCES RESERVATIONS(ID_RESERVATION),
    CONSTRAINT FK_RESERVATION_SEAT FOREIGN KEY (ID_SEAT, ID_SCREEN, ID_SCREENING)
        REFERENCES SEATS(ID_SEAT, ID_SCREEN, ID_SCREENING)
);


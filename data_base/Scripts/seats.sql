CREATE TABLE SEATS(
    ID_SEAT NUMBER,
    SEAT_NUMBER NUMBER CONSTRAINT NN_SEAT_NUMBER NOT NULL,
    SEAT_ROW VARCHAR2(1) CONSTRAINT NN_SEAT_ROW NOT NULL,
    ID_SCREEN NUMBER,
    ID_SCREENING NUMBER,

    CONSTRAINT FK_SEATS_ID_SCREEN FOREIGN KEY (ID_SCREEN) REFERENCES SCREENS(ID_SCREEN),
    CONSTRAINT FK_SEATS_ID_SCREENING FOREIGN KEY (ID_SCREENING) REFERENCES SCREENINGS(ID_SCREENING),
    CONSTRAINT PK_SEAT PRIMARY KEY (ID_SEAT, ID_SCREEN, ID_SCREENING)
);


CREATE TABLE PI_DEVELOPERS.CODES (
    ID_CODE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    HASH VARCHAR2(255) NOT NULL,
    LAST_GENERATED_DATE TIMESTAMP NOT NULL,
    ID_CLIENT NUMBER,
    ID_WORKER NUMBER,

    CONSTRAINT PK_CODES
        PRIMARY KEY (ID_CODE),

    CONSTRAINT FK_CODES_CLIENT
        FOREIGN KEY (ID_CLIENT)
        REFERENCES PI_DEVELOPERS.CLIENTS(ID_CLIENT),

    CONSTRAINT FK_CODES_WORKER
        FOREIGN KEY (ID_WORKER)
        REFERENCES PI_DEVELOPERS.WORKERS(ID_WORKER),

    CONSTRAINT CK_CODES_OWNER
        CHECK (
            (ID_CLIENT IS NOT NULL AND ID_WORKER IS NULL)
            OR
            (ID_CLIENT IS NULL AND ID_WORKER IS NOT NULL)
        )
);
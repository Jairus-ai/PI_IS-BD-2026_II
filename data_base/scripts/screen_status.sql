-- Requires SCREENS (screenrooms.sql) and WORKERS (Workers.sql)

-- Tables
CREATE TABLE SCREEN_STATUS_OVERRIDES (
    ID_SCREEN NUMBER NOT NULL,
    OVERRIDE_STATUS VARCHAR2(10) NOT NULL,
    SET_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    ID_WORKER NUMBER NOT NULL
);

-- Primary Keys
ALTER TABLE SCREEN_STATUS_OVERRIDES ADD CONSTRAINT PK_SCREEN_STATUS_OVERRIDE PRIMARY KEY (ID_SCREEN);

-- Validations
ALTER TABLE SCREEN_STATUS_OVERRIDES ADD CONSTRAINT CHK_OVERRIDE_STATUS
    CHECK (OVERRIDE_STATUS IN ('PLAYING', 'WAITING', 'CLEANING', 'FREE'));

-- Foreign Keys
ALTER TABLE SCREEN_STATUS_OVERRIDES ADD CONSTRAINT FK_OVERRIDE_SCREEN
    FOREIGN KEY (ID_SCREEN) REFERENCES SCREENS(ID_SCREEN);
ALTER TABLE SCREEN_STATUS_OVERRIDES ADD CONSTRAINT FK_OVERRIDE_WORKER
    FOREIGN KEY (ID_WORKER) REFERENCES WORKERS(ID_WORKER);

-- Permissions
GRANT SELECT, INSERT, UPDATE, DELETE ON PI_DEVELOPERS.SCREEN_STATUS_OVERRIDES TO SERVER;
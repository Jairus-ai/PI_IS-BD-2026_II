--Requirements: CLIENTS, SEATS, FEES, SNACKS, DISCOUNTS
--Tables
CREATE TABLE RECEIPTS (
    ID_RECEIPT NUMBER GENERATED ALWAYS AS IDENTITY,
    RECEIPT_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    TOTAL_AMOUNT NUMBER(10, 2) NOT NULL,
    STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
    PAYMENT_TYPE VARCHAR2(20),
    ID_CLIENT NUMBER NOT NULL
);

--Amounts are stored per line so the history keeps the prices paid even if fees or snacks change
CREATE TABLE SEAT_RECEIPTS (
    ID_SEAT_RECEIPT NUMBER GENERATED ALWAYS AS IDENTITY,
    AMOUNT NUMBER(10, 2) NOT NULL,
    ID_RECEIPT NUMBER NOT NULL,
    ID_SEAT NUMBER NOT NULL,
    ID_SCREEN NUMBER NOT NULL,
    ID_SCREENING NUMBER NOT NULL,
    ID_FEE NUMBER NOT NULL
);

CREATE TABLE SNACK_RECEIPTS (
    ID_SNACK_RECEIPT NUMBER GENERATED ALWAYS AS IDENTITY,
    QUANTITY NUMBER NOT NULL,
    UNIT_PRICE NUMBER(10, 2) NOT NULL,
    ID_RECEIPT NUMBER NOT NULL,
    ID_SNACK NUMBER NOT NULL
);

CREATE TABLE RECEIPT_DISCOUNTS (
    ID_RECEIPT_DISCOUNT NUMBER GENERATED ALWAYS AS IDENTITY,
    DISCOUNT_AMOUNT NUMBER(10, 2) NOT NULL,
    ID_RECEIPT NUMBER NOT NULL,
    ID_DISCOUNT NUMBER NOT NULL
);

CREATE TABLE REFUNDS (
    ID_REFUND NUMBER GENERATED ALWAYS AS IDENTITY,
    REFUND_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    AMOUNT NUMBER(10, 2) NOT NULL,
    ID_RECEIPT NUMBER NOT NULL
);

--Primary Keys
ALTER TABLE RECEIPTS ADD CONSTRAINT PK_RECEIPT PRIMARY KEY (ID_RECEIPT);
ALTER TABLE SEAT_RECEIPTS ADD CONSTRAINT PK_SEAT_RECEIPT PRIMARY KEY (ID_SEAT_RECEIPT);
ALTER TABLE SNACK_RECEIPTS ADD CONSTRAINT PK_SNACK_RECEIPT PRIMARY KEY (ID_SNACK_RECEIPT);
ALTER TABLE RECEIPT_DISCOUNTS ADD CONSTRAINT PK_RECEIPT_DISCOUNT PRIMARY KEY (ID_RECEIPT_DISCOUNT);
ALTER TABLE REFUNDS ADD CONSTRAINT PK_REFUND PRIMARY KEY (ID_REFUND);

--Unique, a receipt is refumnded only once
ALTER TABLE REFUNDS ADD CONSTRAINT UQ_REFUND_RECEIPT UNIQUE (ID_RECEIPT);

--Validations
ALTER TABLE RECEIPTS ADD CONSTRAINT CHK_RECEIPT_STATUS CHECK (STATUS IN ('PENDING', 'PAID', 'CANCELLED'));
ALTER TABLE RECEIPTS ADD CONSTRAINT CHK_RECEIPT_TOTAL CHECK (TOTAL_AMOUNT >= 0);
ALTER TABLE SEAT_RECEIPTS ADD CONSTRAINT CHK_SEAT_RECEIPT_AMOUNT CHECK (AMOUNT >= 0);
ALTER TABLE SNACK_RECEIPTS ADD CONSTRAINT CHK_SNACK_RECEIPT_QUANTITY CHECK (QUANTITY > 0);
ALTER TABLE SNACK_RECEIPTS ADD CONSTRAINT CHK_SNACK_RECEIPT_PRICE CHECK (UNIT_PRICE >= 0);
ALTER TABLE RECEIPT_DISCOUNTS ADD CONSTRAINT CHK_RECEIPT_DISCOUNT_AMOUNT CHECK (DISCOUNT_AMOUNT >= 0);
ALTER TABLE REFUNDS ADD CONSTRAINT CHK_REFUND_AMOUNT CHECK (AMOUNT >= 0);

--Foreign Keys
ALTER TABLE RECEIPTS ADD CONSTRAINT FK_RECEIPT_CLIENT
    FOREIGN KEY (ID_CLIENT) REFERENCES CLIENTS(ID_CLIENT);

ALTER TABLE SEAT_RECEIPTS ADD CONSTRAINT FK_SEAT_RECEIPT_RECEIPT
    FOREIGN KEY (ID_RECEIPT) REFERENCES RECEIPTS(ID_RECEIPT);
ALTER TABLE SEAT_RECEIPTS ADD CONSTRAINT FK_SEAT_RECEIPT_SEAT
    FOREIGN KEY (ID_SEAT, ID_SCREEN, ID_SCREENING) REFERENCES SEATS(ID_SEAT, ID_SCREEN, ID_SCREENING);
ALTER TABLE SEAT_RECEIPTS ADD CONSTRAINT FK_SEAT_RECEIPT_FEE
    FOREIGN KEY (ID_FEE) REFERENCES FEES(ID_FEE);

ALTER TABLE SNACK_RECEIPTS ADD CONSTRAINT FK_SNACK_RECEIPT_RECEIPT
    FOREIGN KEY (ID_RECEIPT) REFERENCES RECEIPTS(ID_RECEIPT);
ALTER TABLE SNACK_RECEIPTS ADD CONSTRAINT FK_SNACK_RECEIPT_SNACK
    FOREIGN KEY (ID_SNACK) REFERENCES SNACKS(ID_SNACK);

ALTER TABLE RECEIPT_DISCOUNTS ADD CONSTRAINT FK_RECEIPT_DISCOUNT_RECEIPT
    FOREIGN KEY (ID_RECEIPT) REFERENCES RECEIPTS(ID_RECEIPT);
ALTER TABLE RECEIPT_DISCOUNTS ADD CONSTRAINT FK_RECEIPT_DISCOUNT_DISCOUNT
    FOREIGN KEY (ID_DISCOUNT) REFERENCES DISCOUNTS(ID_DISCOUNT);

ALTER TABLE REFUNDS ADD CONSTRAINT FK_REFUND_RECEIPT
    FOREIGN KEY (ID_RECEIPT) REFERENCES RECEIPTS(ID_RECEIPT);

--Indexes for clients purchase history
CREATE INDEX IX_RECEIPT_CLIENT ON RECEIPTS (ID_CLIENT);
CREATE INDEX IX_SEAT_RECEIPT_RECEIPT ON SEAT_RECEIPTS (ID_RECEIPT);
CREATE INDEX IX_SNACK_RECEIPT_RECEIPT ON SNACK_RECEIPTS (ID_RECEIPT);

--Permissions
GRANT SELECT, INSERT, UPDATE, DELETE ON PI_DEVELOPERS.RECEIPTS TO SERVER;
GRANT SELECT, INSERT, UPDATE, DELETE ON PI_DEVELOPERS.SEAT_RECEIPTS TO SERVER;
GRANT SELECT, INSERT, UPDATE, DELETE ON PI_DEVELOPERS.SNACK_RECEIPTS TO SERVER;
GRANT SELECT, INSERT, UPDATE, DELETE ON PI_DEVELOPERS.RECEIPT_DISCOUNTS TO SERVER;
GRANT SELECT, INSERT, UPDATE, DELETE ON PI_DEVELOPERS.REFUNDS TO SERVER;
GRANT SELECT ON PI_DEVELOPERS.SCREENINGS TO SERVER;
GRANT SELECT ON PI_DEVELOPERS.SCREENS TO SERVER;
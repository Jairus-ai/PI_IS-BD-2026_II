ALTER TABLE MOVIES_IN_BILLBOARDS ADD CONSTRAINT PK_MIB PRIMARY KEY (ID_MOVIE_IN_BILLBOARD);
ALTER TABLE SCREENINGS ADD CONSTRAINT PK_SCREENINGS PRIMARY KEY (ID_SCREENING);

-- Deletion
ALTER TABLE MOVIES_IN_BILLBOARDS ADD CONSTRAINT CHK_MIB_DELETED CHECK (IS_DELETED IN (0, 1));
ALTER TABLE SCREENINGS ADD CONSTRAINT CHK_SCREENING_DELETED CHECK (IS_DELETED IN (0, 1));

-- Validations
ALTER TABLE MOVIES_IN_BILLBOARDS ADD CONSTRAINT CHK_MIB_PREMIER CHECK (PREMIER IN (0, 1));


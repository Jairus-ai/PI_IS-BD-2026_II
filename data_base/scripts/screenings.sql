-- Tables
CREATE TABLE MOVIES_IN_BILLBOARDS (
    ID_MOVIE_IN_BILLBOARD NUMBER GENERATED ALWAYS AS IDENTITY,
    OPENING_DATE DATE NOT NULL,
    CLOSING_DATE DATE NOT NULL,
    PREMIER NUMBER(1) DEFAULT 0 NOT NULL,
    ID_LOCATION NUMBER NOT NULL,
    ID_MOVIE NUMBER NOT NULL,
    IS_DELETED NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE SCREENINGS (
    ID_SCREENING NUMBER GENERATED ALWAYS AS IDENTITY,
    SCREENING_DATE DATE NOT NULL,
    SCREENING_START_TIME INTERVAL DAY(0) TO SECOND(0) NOT NULL,
    SCREENING_END_TIME INTERVAL DAY(0) TO SECOND(0) NOT NULL,
    MOVIE_LANGUAGE VARCHAR2(50) NOT NULL,
    MOVIE_FORMAT VARCHAR2(50) NOT NULL,
    ID_SCREEN NUMBER NOT NULL,
    ID_MOVIE_IN_BILLBOARD NUMBER NOT NULL,
    IS_DELETED NUMBER(1) DEFAULT 0 NOT NULL
);

